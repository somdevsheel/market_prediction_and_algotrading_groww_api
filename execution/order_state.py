"""Explicit order lifecycle state machine."""
from __future__ import annotations

from enum import Enum


class OrderState(str, Enum):
    CREATED = "CREATED"
    VALIDATED = "VALIDATED"
    SUBMITTED = "SUBMITTED"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    OPEN = "OPEN"
    PARTIALLY_FILLED = "PARTIALLY_FILLED"
    FILLED = "FILLED"
    EXIT_PENDING = "EXIT_PENDING"
    CLOSED = "CLOSED"
    REJECTED = "REJECTED"
    CANCELLED = "CANCELLED"
    EXPIRED = "EXPIRED"
    UNKNOWN = "UNKNOWN"
    RECONCILIATION_REQUIRED = "RECONCILIATION_REQUIRED"


S = OrderState
TERMINAL = {S.FILLED, S.CLOSED, S.REJECTED, S.CANCELLED, S.EXPIRED}
WORKING = {S.SUBMITTED, S.ACKNOWLEDGED, S.OPEN, S.PARTIALLY_FILLED, S.UNKNOWN, S.RECONCILIATION_REQUIRED}

_ANY_BROKER = {S.ACKNOWLEDGED, S.OPEN, S.PARTIALLY_FILLED, S.FILLED, S.REJECTED, S.CANCELLED, S.EXPIRED, S.UNKNOWN,
               S.RECONCILIATION_REQUIRED}
ALLOWED: dict[OrderState, set[OrderState]] = {
    S.CREATED: {S.VALIDATED, S.REJECTED},
    S.VALIDATED: {S.SUBMITTED, S.REJECTED, S.CANCELLED},
    S.SUBMITTED: _ANY_BROKER,
    S.ACKNOWLEDGED: _ANY_BROKER - {S.ACKNOWLEDGED},
    S.OPEN: _ANY_BROKER - {S.ACKNOWLEDGED},
    S.PARTIALLY_FILLED: {S.PARTIALLY_FILLED, S.FILLED, S.CANCELLED, S.EXPIRED, S.UNKNOWN, S.RECONCILIATION_REQUIRED},
    S.UNKNOWN: _ANY_BROKER,
    S.RECONCILIATION_REQUIRED: _ANY_BROKER,
    S.FILLED: {S.EXIT_PENDING, S.CLOSED},
    S.EXIT_PENDING: {S.CLOSED, S.FILLED},
    S.CLOSED: set(),
    S.REJECTED: set(),
    S.CANCELLED: set(),
    S.EXPIRED: set(),
}


class InvalidTransition(RuntimeError):
    pass


def check_transition(old: OrderState, new: OrderState) -> None:
    if old == new and old in (S.OPEN, S.PARTIALLY_FILLED, S.UNKNOWN):
        return
    if new not in ALLOWED[old]:
        raise InvalidTransition(f"{old.value} -> {new.value}")


# Groww order_status strings -> internal states (unknown strings map to UNKNOWN, never assumed filled)
GROWW_STATUS_MAP = {
    "NEW": S.ACKNOWLEDGED, "ACKED": S.ACKNOWLEDGED, "APPROVED": S.OPEN, "OPEN": S.OPEN,
    "TRIGGER_PENDING": S.OPEN, "MODIFICATION_REQUESTED": S.OPEN, "CANCELLATION_REQUESTED": S.OPEN,
    "EXECUTED": S.FILLED, "COMPLETED": S.FILLED, "DELIVERY_AWAITED": S.FILLED, "DELIVERY_AWAITING": S.FILLED,
    "REJECTED": S.REJECTED, "FAILED": S.REJECTED, "CANCELLED": S.CANCELLED, "EXPIRED": S.EXPIRED,
}
